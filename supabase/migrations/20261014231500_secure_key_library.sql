-- One-minute atomic rate limit buckets used by the server-side Key Library API.
create table if not exists public.key_library_rate_limits (
  scope_hash text not null check (scope_hash ~ '^[a-f0-9]{64}$'),
  bucket_start timestamptz not null,
  request_count integer not null default 0,
  primary key (scope_hash, bucket_start)
);
alter table public.key_library_rate_limits enable row level security;
revoke all on table public.key_library_rate_limits from public, anon, authenticated;
grant select, insert, update, delete on table public.key_library_rate_limits to service_role;

create or replace function public.bdz_key_library_rate_limit(
  p_scope_hash text,
  p_max_requests integer
)
returns boolean
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_bucket timestamptz := date_trunc('minute', now());
  v_count integer;
begin
  if p_scope_hash is null or p_scope_hash !~ '^[a-f0-9]{64}$'
     or p_max_requests is null or p_max_requests < 1 or p_max_requests > 300 then
    return false;
  end if;

  insert into public.key_library_rate_limits(scope_hash, bucket_start, request_count)
  values (p_scope_hash, v_bucket, 1)
  on conflict (scope_hash, bucket_start)
  do update set request_count = public.key_library_rate_limits.request_count + 1
  returning request_count into v_count;

  delete from public.key_library_rate_limits
  where bucket_start < v_bucket - interval '10 minutes';

  return v_count <= p_max_requests;
end;
$function$;

revoke all on function public.bdz_key_library_rate_limit(text, integer) from public, anon, authenticated;
grant execute on function public.bdz_key_library_rate_limit(text, integer) to service_role;

-- Used only by the server-side web-get-key function. The original three-argument
-- function is no longer callable by browser roles, preventing an untracked claim path.
create or replace function public.bdz_web_claim_key_vault(
  p_token text,
  p_ip text,
  p_visitor_id text,
  p_owner_token_hash text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  h text;
  ctx text;
  t public.key_claim_tokens%rowtype;
  code text;
  k public.app_keys%rowtype;
  sett public.system_settings%rowtype;
  dur integer := 5;
  maxd integer := 1;
  maxc integer := 0;
begin
  if p_owner_token_hash is null or p_owner_token_hash !~ '^[a-f0-9]{64}$' then
    return jsonb_build_object('ok', false, 'error', 'LIBRARY_TOKEN_INVALID');
  end if;

  select * into sett from public.system_settings where id = true;
  if found then
    dur := sett.default_duration_hours;
    maxd := sett.default_max_devices;
    maxc := sett.default_max_checks;
  end if;

  h := public.bdz_hash(trim(coalesce(p_token, '')));
  ctx := public.bdz_hash(coalesce(p_ip, 'unknown') || '|' || coalesce(p_visitor_id, 'unknown'));

  select * into t from public.key_claim_tokens where token_hash = h limit 1 for update;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'Token không tồn tại hoặc không hợp lệ.');
  end if;

  if t.status = 'USED' then
    return jsonb_build_object('ok', false, 'error', 'Token đã được sử dụng.');
  end if;

  if t.status <> 'PENDING' or t.expires_at <= now() then
    if t.status = 'PENDING' then
      update public.key_claim_tokens set status = 'EXPIRED' where id = t.id and status = 'PENDING';
    end if;
    return jsonb_build_object('ok', false, 'error', 'Token đã hết hạn. Vui lòng nhận key lại.');
  end if;

  if t.context_hash is not null and t.context_hash <> ctx then
    return jsonb_build_object('ok', false, 'error', 'Phiên không khớp. Hãy mở link trên cùng thiết bị.');
  end if;

  update public.key_claim_tokens
  set status = 'USED', used_at = now()
  where id = t.id and status = 'PENDING' and expires_at > now()
    and (context_hash is null or context_hash = ctx);

  if not found then
    return jsonb_build_object('ok', false, 'error', 'Token đã được sử dụng.');
  end if;

  loop
    code := substring(md5(gen_random_bytes(24)::text || clock_timestamp()::text || random()::text) from 1 for 16);
    exit when not exists(select 1 from public.app_keys where key_code = code);
  end loop;

  insert into public.app_keys(
    key_code, key_fingerprint, status, duration_hours, expires_at,
    max_devices, check_count, max_checks
  )
  values (
    code, public.bdz_hash(code), 'ACTIVE', dur,
    now() + make_interval(hours => dur), maxd, 0, maxc
  )
  returning * into k;

  insert into public.key_library_access(owner_token_hash, key_id, source)
  values (p_owner_token_hash, k.id, 'GET');

  return jsonb_build_object('ok', true, 'key', jsonb_build_object(
    'key_code', k.key_code, 'status', k.status, 'expires_at', k.expires_at,
    'duration_hours', k.duration_hours, 'max_checks', k.max_checks,
    'max_devices', k.max_devices, 'created_at', k.created_at
  ));
exception when others then
  update public.key_claim_tokens set status = 'PENDING', used_at = null
  where token_hash = h and status = 'USED' and used_at is not null
    and used_at > now() - interval '2 minutes';
  raise;
end;
$function$;

revoke all on function public.bdz_web_claim_key_vault(text, text, text, text) from public, anon, authenticated;
grant execute on function public.bdz_web_claim_key_vault(text, text, text, text) to service_role;
revoke all on function public.bdz_web_claim(text, text, text) from public, anon, authenticated;
grant execute on function public.bdz_web_claim(text, text, text) to service_role;

-- Replace settlement so paid keys are attached to their private library in the same transaction.
create or replace function public.bdz_pay2s_settle(
  p_order_id text,
  p_request_id text,
  p_partner_code text,
  p_amount bigint,
  p_result_code integer,
  p_trans_id text,
  p_message text
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'extensions'
as $function$
declare
  v_order public.pay2s_orders%rowtype;
  v_settings public.pay2s_settings%rowtype;
  v_key_code text;
  v_key_id bigint;
  v_new_status text;
begin
  select * into v_order from public.pay2s_orders
  where order_id = p_order_id for update;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'ORDER_NOT_FOUND');
  end if;

  select * into v_settings from public.pay2s_settings where id = true;

  -- IPN requestId is recorded for audit but can differ from create-order requestId.
  if p_partner_code is distinct from v_settings.partner_code
     or p_amount is distinct from v_order.amount then
    return jsonb_build_object('ok', false, 'error', 'PAYMENT_MISMATCH');
  end if;

  if v_order.status = 'PAID' then
    if v_order.owner_token_hash is not null and v_order.key_id is not null then
      insert into public.key_library_access(owner_token_hash, key_id, source, order_id)
      values (v_order.owner_token_hash, v_order.key_id, 'PURCHASE', v_order.order_id)
      on conflict (key_id) do nothing;
    end if;
    return jsonb_build_object('ok', true, 'duplicate', true, 'status', 'PAID');
  end if;

  if p_result_code = 0 then
    v_key_code := upper(encode(extensions.gen_random_bytes(12), 'hex'));
    insert into public.app_keys(
      key_code, key_fingerprint, status, duration_hours, expires_at,
      max_devices, check_count, max_checks, created_by_admin_id
    ) values (
      v_key_code, public.bdz_hash(v_key_code), 'ACTIVE',
      v_order.duration_hours, now() + make_interval(hours => v_order.duration_hours),
      v_order.max_devices, 0, 0, null
    ) returning id into v_key_id;

    update public.pay2s_orders set
      status = 'PAID',
      pay2s_ipn_request_id = nullif(p_request_id, ''),
      pay2s_trans_id = coalesce(nullif(p_trans_id, ''), pay2s_trans_id),
      result_code = p_result_code,
      result_message = left(coalesce(p_message, ''), 300),
      key_id = v_key_id,
      paid_at = now()
    where id = v_order.id;

    if v_order.owner_token_hash is not null then
      insert into public.key_library_access(owner_token_hash, key_id, source, order_id)
      values (v_order.owner_token_hash, v_key_id, 'PURCHASE', v_order.order_id);
    end if;

    return jsonb_build_object('ok', true, 'duplicate', false, 'status', 'PAID');
  end if;

  v_new_status := case when p_result_code = 9000 then 'PENDING' else 'FAILED' end;
  update public.pay2s_orders set
    pay2s_ipn_request_id = nullif(p_request_id, ''),
    pay2s_trans_id = coalesce(nullif(p_trans_id, ''), pay2s_trans_id),
    result_code = p_result_code,
    result_message = left(coalesce(p_message, ''), 300),
    status = v_new_status
  where id = v_order.id;

  return jsonb_build_object('ok', true, 'status', v_new_status);
end;
$function$;

revoke all on function public.bdz_pay2s_settle(text, text, text, bigint, integer, text, text) from public, anon, authenticated;
grant execute on function public.bdz_pay2s_settle(text, text, text, bigint, integer, text, text) to service_role;
