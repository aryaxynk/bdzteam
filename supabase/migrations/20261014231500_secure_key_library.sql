-- Private Key Library: unguessable browser-held bearer credential; only hashes are stored server-side.
alter table public.pay2s_orders
  add column if not exists owner_token_hash text;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'pay2s_orders_owner_token_hash_format'
      and conrelid = 'public.pay2s_orders'::regclass
  ) then
    alter table public.pay2s_orders
      add constraint pay2s_orders_owner_token_hash_format
      check (owner_token_hash is null or owner_token_hash ~ '^[a-f0-9]{64}$');
  end if;
end $$;

create table if not exists public.key_library_access (
  key_id bigint primary key references public.app_keys(id) on delete cascade,
  owner_token_hash text not null check (owner_token_hash ~ '^[a-f0-9]{64}$'),
  source text not null check (source in ('GET','PURCHASE')),
  order_id text references public.pay2s_orders(order_id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists key_library_access_owner_created_idx
  on public.key_library_access(owner_token_hash, created_at desc);

