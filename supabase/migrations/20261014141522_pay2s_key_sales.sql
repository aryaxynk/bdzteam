-- Pay2S checkout and key fulfillment for BDZMOD.
-- Credentials are stored in Supabase Vault and are only readable by service_role functions.

create table if not exists public.pay2s_settings (
  id boolean primary key default true check (id = true),
  enabled boolean not null default false,
  environment text not null default 'sandbox' check (environment in ('sandbox','production')),
  partner_code text,
  partner_name text not null default 'BDZMOD',
  bank_accounts jsonb not null default '[]'::jsonb check (jsonb_typeof(bank_accounts) = 'array'),
  updated_by_admin_id bigint references public.admins(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.pay2s_settings (id) values (true)
on conflict (id) do nothing;

create table if not exists public.pay2s_packages (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null check (char_length(name) between 2 and 100),
  description text,
  amount bigint not null check (amount > 0 and amount <= 1000000000),
  duration_hours integer not null check (duration_hours between 1 and 8760),
  max_devices integer not null default 1 check (max_devices between 1 and 100),
  enabled boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.pay2s_orders (
  id uuid primary key default gen_random_uuid(),
  order_id text not null unique check (char_length(order_id) between 10 and 64),
  request_id text not null unique check (char_length(request_id) between 1 and 50),
  package_id bigint references public.pay2s_packages(id) on delete set null,
  package_code text,
  package_name text not null,
  amount bigint not null check (amount > 0),
  duration_hours integer not null check (duration_hours between 1 and 8760),
  max_devices integer not null check (max_devices between 1 and 100),
  status text not null default 'PENDING' check (status in ('PENDING','PAID','FAILED','EXPIRED')),
  view_token_hash text not null,
  pay2s_trans_id text,
  result_code integer,
  result_message text,
  key_id bigint references public.app_keys(id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '30 minutes'),
  paid_at timestamptz
);

create index if not exists pay2s_orders_status_created_idx on public.pay2s_orders(status, created_at desc);
create index if not exists pay2s_orders_package_idx on public.pay2s_orders(package_id);

alter table public.pay2s_settings enable row level security;
alter table public.pay2s_packages enable row level security;
alter table public.pay2s_orders enable row level security;

revoke all on table public.pay2s_settings from anon, authenticated;
revoke all on table public.pay2s_packages from anon, authenticated;
revoke all on table public.pay2s_orders from anon, authenticated;
grant select, insert, update, delete on table public.pay2s_settings to service_role;
grant select, insert, update, delete on table public.pay2s_packages to service_role;
grant select, insert, update, delete on table public.pay2s_orders to service_role;
grant usage, select on sequence public.pay2s_packages_id_seq to service_role;

CREATE OR REPLACE FUNCTION public.bdz_pay2s_admin_config(p_token text, p_action text, p_payload jsonb DEFAULT '{}'::jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'vault'
AS $function$
declare
  v_admin_id bigint;
  v_role text;
  v_settings public.pay2s_settings%rowtype;
  v_packages jsonb;
  v_id bigint;
  v_name text;
  v_description text;
  v_amount bigint;
  v_duration integer;
  v_devices integer;
  v_enabled boolean;
  v_sort integer;
  v_environment text;
  v_partner_code text;
  v_partner_name text;
  v_bank_accounts jsonb;
  v_access_key text;
  v_secret_key text;
  v_access_set boolean;
  v_secret_set boolean;
  v_secret_id uuid;
  v_package_code text;
begin
  select a.id, a.role into v_admin_id, v_role
  from public.admin_sessions s
  join public.admins a on a.id = s.admin_id
  where s.session_hash = public.bdz_hash(trim(coalesce(p_token, '')))
    and s.revoked_at is null
    and s.expires_at > now()
    and a.active = true
  limit 1;

  if v_admin_id is null then
    return jsonb_build_object('ok', false, 'error', 'UNAUTHORIZED');
  end if;

  select * into v_settings from public.pay2s_settings where id = true;
  if not found then
    insert into public.pay2s_settings (id) values (true)
    on conflict (id) do nothing;
    select * into v_settings from public.pay2s_settings where id = true;
  end if;

  if p_action = 'get' then
    select coalesce(jsonb_agg(to_jsonb(p) order by p.sort_order, p.id), '[]'::jsonb)
      into v_packages from public.pay2s_packages p;
    return jsonb_build_object(
      'ok', true,
      'settings', to_jsonb(v_settings) - 'updated_by_admin_id',
      'packages', v_packages,
      'access_key_set', exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_ACCESS_KEY'),
      'secret_key_set', exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_SECRET_KEY'),
      'ipn_url', 'https://nklukqriopezsoalnghm.supabase.co/functions/v1/pay2s-ipn',
      'return_url', 'https://aryaxynk.github.io/bdzteam/payment/return.html'
    );
  end if;

  if p_action = 'save_settings' then
    if v_role <> 'OWNER' then
      return jsonb_build_object('ok', false, 'error', 'OWNER_REQUIRED');
    end if;

    v_environment := case
      when p_payload->>'environment' in ('sandbox','production') then p_payload->>'environment'
      else v_settings.environment
    end;
    v_partner_code := case when p_payload ? 'partner_code'
      then nullif(trim(p_payload->>'partner_code'), '') else v_settings.partner_code end;
    v_partner_name := case when p_payload ? 'partner_name'
      then coalesce(nullif(trim(p_payload->>'partner_name'), ''), 'BDZMOD') else v_settings.partner_name end;
    v_bank_accounts := case when p_payload ? 'bank_accounts'
      then p_payload->'bank_accounts' else v_settings.bank_accounts end;
    v_enabled := case when p_payload ? 'enabled'
      then coalesce((p_payload->>'enabled')::boolean, false) else v_settings.enabled end;
    v_access_key := nullif(trim(p_payload->>'access_key'), '');
    v_secret_key := nullif(trim(p_payload->>'secret_key'), '');

    if jsonb_typeof(v_bank_accounts) is distinct from 'array' then
      return jsonb_build_object('ok', false, 'error', 'BANK_ACCOUNTS_INVALID');
    end if;
    if exists (
      select 1
      from jsonb_array_elements(v_bank_accounts) b
      where length(trim(coalesce(b->>'account_number',''))) < 3
         or length(trim(coalesce(b->>'account_number',''))) > 64
         or length(trim(coalesce(b->>'bank_id',''))) < 2
         or length(trim(coalesce(b->>'bank_id',''))) > 24
    ) then
      return jsonb_build_object('ok', false, 'error', 'BANK_ACCOUNTS_INVALID');
    end if;

    v_access_set := v_access_key is not null
      or exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_ACCESS_KEY');
    v_secret_set := v_secret_key is not null
      or exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_SECRET_KEY');

    if v_enabled then
      if v_partner_code is null or jsonb_array_length(v_bank_accounts) = 0 or not v_access_set or not v_secret_set then
        return jsonb_build_object('ok', false, 'error', 'PAY2S_CONFIG_INCOMPLETE');
      end if;
      if not exists(select 1 from public.pay2s_packages where enabled = true) then
        return jsonb_build_object('ok', false, 'error', 'NO_ENABLED_PACKAGES');
      end if;
    end if;

    if v_access_key is not null then
      select id into v_secret_id from vault.secrets
      where name = 'BDZMOD_PAY2S_ACCESS_KEY'
      order by updated_at desc limit 1;
      if v_secret_id is null then
        perform vault.create_secret(v_access_key, 'BDZMOD_PAY2S_ACCESS_KEY', 'Pay2S access key for BDZMOD payment function');
      else
        perform vault.update_secret(secret_id := v_secret_id, new_secret := v_access_key,
          new_description := 'Pay2S access key for BDZMOD payment function');
      end if;
    end if;

    if v_secret_key is not null then
      v_secret_id := null;
      select id into v_secret_id from vault.secrets
      where name = 'BDZMOD_PAY2S_SECRET_KEY'
      order by updated_at desc limit 1;
      if v_secret_id is null then
        perform vault.create_secret(v_secret_key, 'BDZMOD_PAY2S_SECRET_KEY', 'Pay2S signing key for BDZMOD payment function');
      else
        perform vault.update_secret(secret_id := v_secret_id, new_secret := v_secret_key,
          new_description := 'Pay2S signing key for BDZMOD payment function');
      end if;
    end if;

    update public.pay2s_settings set
      enabled = v_enabled,
      environment = v_environment,
      partner_code = v_partner_code,
      partner_name = v_partner_name,
      bank_accounts = v_bank_accounts,
      updated_by_admin_id = v_admin_id,
      updated_at = now()
    where id = true;

    return jsonb_build_object(
      'ok', true,
      'enabled', v_enabled,
      'access_key_set', exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_ACCESS_KEY'),
      'secret_key_set', exists(select 1 from vault.secrets where name = 'BDZMOD_PAY2S_SECRET_KEY')
    );
  end if;

  if p_action in ('save_package','toggle_package','delete_package') then
    if v_role not in ('OWNER','ADMIN') then
      return jsonb_build_object('ok', false, 'error', 'FORBIDDEN');
    end if;
  end if;

  if p_action = 'save_package' then
    v_id := nullif(trim(p_payload->>'id'), '')::bigint;
    v_name := nullif(trim(p_payload->>'name'), '');
    v_description := nullif(trim(p_payload->>'description'), '');
    v_amount := nullif(trim(p_payload->>'amount'), '')::bigint;
    v_duration := nullif(trim(p_payload->>'duration_hours'), '')::integer;
    v_devices := nullif(trim(p_payload->>'max_devices'), '')::integer;
    v_enabled := coalesce((p_payload->>'enabled')::boolean, true);
    v_sort := coalesce(nullif(trim(p_payload->>'sort_order'), '')::integer, 0);

    if v_name is null or char_length(v_name) < 2 or char_length(v_name) > 100 then
      return jsonb_build_object('ok', false, 'error', 'INVALID_PACKAGE_NAME');
    end if;
    if v_amount is null or v_amount < 1 or v_amount > 1000000000 then
      return jsonb_build_object('ok', false, 'error', 'INVALID_PACKAGE_AMOUNT');
    end if;
    if v_duration is null or v_duration < 1 or v_duration > 8760 then
      return jsonb_build_object('ok', false, 'error', 'INVALID_PACKAGE_DURATION');
    end if;
    if v_devices is null or v_devices < 1 or v_devices > 100 then
      return jsonb_build_object('ok', false, 'error', 'INVALID_PACKAGE_DEVICES');
    end if;

    if v_id is null then
      v_package_code := 'BDZP' || upper(substring(encode(extensions.gen_random_bytes(5), 'hex') from 1 for 10));
      insert into public.pay2s_packages(code,name,description,amount,duration_hours,max_devices,enabled,sort_order)
      values (v_package_code,v_name,v_description,v_amount,v_duration,v_devices,v_enabled,v_sort)
      returning id into v_id;
    else
      update public.pay2s_packages set
        name = v_name,
        description = v_description,
        amount = v_amount,
        duration_hours = v_duration,
        max_devices = v_devices,
        enabled = v_enabled,
        sort_order = v_sort,
        updated_at = now()
      where id = v_id
      returning id into v_id;
      if not found then
        return jsonb_build_object('ok', false, 'error', 'PACKAGE_NOT_FOUND');
      end if;
    end if;
    return jsonb_build_object('ok', true, 'id', v_id);
  end if;

  if p_action = 'toggle_package' then
    v_id := nullif(trim(p_payload->>'id'), '')::bigint;
    update public.pay2s_packages set enabled = not enabled, updated_at = now()
    where id = v_id returning enabled into v_enabled;
    if not found then return jsonb_build_object('ok', false, 'error', 'PACKAGE_NOT_FOUND'); end if;
    return jsonb_build_object('ok', true, 'enabled', v_enabled);
  end if;

  if p_action = 'delete_package' then
    v_id := nullif(trim(p_payload->>'id'), '')::bigint;
    if exists(select 1 from public.pay2s_orders where package_id = v_id) then
      update public.pay2s_packages set enabled = false, updated_at = now() where id = v_id;
      return jsonb_build_object('ok', true, 'disabled', true);
    end if;
    delete from public.pay2s_packages where id = v_id;
    return jsonb_build_object('ok', true, 'deleted', true);
  end if;

  return jsonb_build_object('ok', false, 'error', 'UNKNOWN_ACTION');
exception when others then
  -- Never return SQL exception detail because it may contain privileged data.
  return jsonb_build_object('ok', false, 'error', 'CONFIG_OPERATION_FAILED');
end;
$function$


revoke all on function public.bdz_pay2s_admin_config(text,text,jsonb) from public;
grant execute on function public.bdz_pay2s_admin_config(text,text,jsonb) to anon, authenticated;

CREATE OR REPLACE FUNCTION public.bdz_pay2s_backend_config()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'vault'
AS $function$
declare
  v_settings public.pay2s_settings%rowtype;
  v_access text;
  v_secret text;
begin
  select * into v_settings from public.pay2s_settings where id = true;
  select decrypted_secret into v_access from vault.decrypted_secrets
    where name = 'BDZMOD_PAY2S_ACCESS_KEY' order by updated_at desc limit 1;
  select decrypted_secret into v_secret from vault.decrypted_secrets
    where name = 'BDZMOD_PAY2S_SECRET_KEY' order by updated_at desc limit 1;
  return jsonb_build_object(
    'ok', true,
    'access_key', v_access,
    'secret_key', v_secret,
    'settings', to_jsonb(v_settings)
  );
end;
$function$


revoke all on function public.bdz_pay2s_backend_config() from public, anon, authenticated;
grant execute on function public.bdz_pay2s_backend_config() to service_role;

CREATE OR REPLACE FUNCTION public.bdz_pay2s_settle(p_order_id text, p_request_id text, p_partner_code text, p_amount bigint, p_result_code integer, p_trans_id text, p_message text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions'
AS $function$
declare
  v_order public.pay2s_orders%rowtype;
  v_settings public.pay2s_settings%rowtype;
  v_key_code text;
  v_key_id bigint;
  v_new_status text;
begin
  select * into v_order from public.pay2s_orders
    where order_id = p_order_id for update;
  if not found then
    return jsonb_build_object('ok', false, 'error', 'ORDER_NOT_FOUND');
  end if;

  select * into v_settings from public.pay2s_settings where id = true;
  if p_partner_code is distinct from v_settings.partner_code
     or p_request_id is distinct from v_order.request_id
     or p_amount is distinct from v_order.amount then
    return jsonb_build_object('ok', false, 'error', 'PAYMENT_MISMATCH');
  end if;

  if v_order.status = 'PAID' then
    return jsonb_build_object('ok', true, 'duplicate', true, 'status', 'PAID');
  end if;

  if p_result_code = 0 then
    v_key_code := upper(encode(extensions.gen_random_bytes(12), 'hex'));
    insert into public.app_keys(
      key_code, key_fingerprint, status, duration_hours, expires_at,
      max_devices, check_count, max_checks, created_by_admin_id
    ) values (
      v_key_code, public.bdz_hash(v_key_code), 'ACTIVE',
      v_order.duration_hours, now() + make_interval(hours => v_order.duration_hours),
      v_order.max_devices, 0, 0, null
    ) returning id into v_key_id;

    update public.pay2s_orders set
      status = 'PAID',
      pay2s_trans_id = coalesce(nullif(p_trans_id,''), pay2s_trans_id),
      result_code = p_result_code,
      result_message = left(coalesce(p_message,''), 300),
      key_id = v_key_id,
      paid_at = now()
    where id = v_order.id;
    return jsonb_build_object('ok', true, 'duplicate', false, 'status', 'PAID');
  end if;

  v_new_status := case when p_result_code = 9000 then 'PENDING' else 'FAILED' end;
  update public.pay2s_orders set
    status = v_new_status,
    pay2s_trans_id = coalesce(nullif(p_trans_id,''), pay2s_trans_id),
    result_code = p_result_code,
    result_message = left(coalesce(p_message,''), 300)
  where id = v_order.id;
  return jsonb_build_object('ok', true, 'status', v_new_status);
end;
$function$


revoke all on function public.bdz_pay2s_settle(text,text,text,bigint,integer,text,text) from public, anon, authenticated;
grant execute on function public.bdz_pay2s_settle(text,text,text,bigint,integer,text,text) to service_role;
